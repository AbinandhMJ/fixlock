'use strict';
// CHANGELOG.md in Keep a Changelog style, built from locks + Conventional Commits since the last release.
const fs = require('fs');
const path = require('path');
const g = require('./git');
const s = require('./store');
const team = require('./team');

const START = '<!-- fixlock:unreleased:start -->';
const END = '<!-- fixlock:unreleased:end -->';
const SECTIONS = [['Added', ['feat']], ['Fixed', ['fix']], ['Changed', ['perf', 'refactor', 'revert']], ['Security', ['security', 'sec']]];

/** Conventional commits in (since, HEAD]. */
function commits(since) {
  const range = since ? [`${since}..HEAD`] : ['HEAD'];
  const out = g.git(['log', '--no-merges', '--pretty=format:%h%x1f%s%x1f%an%x1e', ...range], { allowFail: true }) || '';
  return out.split('\x1e').map((r) => r.trim()).filter(Boolean).map((r) => {
    const [hash, subject, author] = r.split('\x1f');
    const m = subject.match(/^(\w+)(?:\(([^)]+)\))?(!)?:\s*(.+)$/);
    return m ? { hash, type: m[1].toLowerCase(), scope: m[2], breaking: !!m[3], text: m[4], author } : null;
  }).filter(Boolean);
}

function unreleased(cfg, reg) {
  const groups = Object.fromEntries(SECTIONS.map(([n]) => [n, []]));
  const breaking = [];
  for (const l of reg.locks.filter((x) => !x.release)) {
    const owner = team.handle(team.find(cfg, l.owner)) || l.owner;
    const line = `- ${l.title} (${l.id}, ${owner}${l.issue ? ', ' + l.issue : ''})`;
    groups[l.type === 'feature' ? 'Added' : 'Fixed'].push(line);
  }
  const since = reg.lastRelease && reg.lastRelease.sha;
  for (const c of commits(since)) {
    if (/^fixlock\b|^chore/i.test(c.text)) continue;
    const sec = SECTIONS.find(([, types]) => types.includes(c.type));
    const line = `- ${c.scope ? `**${c.scope}:** ` : ''}${c.text} (${c.hash})`;
    if (c.breaking) breaking.push(line);
    if (sec && !groups[sec[0]].some((x) => x.includes(c.text))) groups[sec[0]].push(line);
  }
  let md = '';
  if (breaking.length) md += `### ⚠ Breaking\n${breaking.join('\n')}\n\n`;
  for (const [name] of SECTIONS) if (groups[name].length) md += `### ${name}\n${groups[name].join('\n')}\n\n`;
  return md || '_No changes yet._\n\n';
}

function file() { return path.join(s.root(), 'CHANGELOG.md'); }

function read() {
  return fs.existsSync(file()) ? fs.readFileSync(file(), 'utf8')
    : '# Changelog\n\nAll notable changes to this project. Format: [Keep a Changelog](https://keepachangelog.com), generated by fixlock.\n';
}

/** Refresh the [Unreleased] section. */
function update() {
  const cfg = s.loadConfig();
  const reg = s.loadRegistry();
  const block = `${START}\n## [Unreleased]\n\n${unreleased(cfg, reg)}${END}`;
  let text = read();
  const re = new RegExp(`${START}[\\s\\S]*?${END}`);
  if (re.test(text)) text = text.replace(re, block);
  else {
    const firstRelease = text.search(/^## \[/m);
    text = firstRelease === -1 ? text.trimEnd() + '\n\n' + block + '\n' : text.slice(0, firstRelease) + block + '\n\n' + text.slice(firstRelease);
  }
  fs.writeFileSync(file(), text);
  return file();
}

/** Freeze [Unreleased] as a version, stamp locks, remember the commit. */
function release(version) {
  if (!version) throw new Error('Usage: fixlock release <version>   e.g. fixlock release 1.4.0');
  const cfg = s.loadConfig();
  const reg = s.loadRegistry();
  const date = new Date().toISOString().slice(0, 10);
  const frozen = `## [${version}] - ${date}\n\n${unreleased(cfg, reg)}`.trimEnd() + '\n';
  for (const l of reg.locks) if (!l.release) l.release = version;
  reg.lastRelease = { version, date, sha: (g.git(['rev-parse', 'HEAD'], { allowFail: true }) || '').trim() || null };
  s.saveRegistry(reg);
  let text = read();
  const re = new RegExp(`${START}[\\s\\S]*?${END}`);
  const empty = `${START}\n## [Unreleased]\n\n_No changes yet._\n\n${END}`;
  text = re.test(text) ? text.replace(re, `${empty}\n\n${frozen}`) : text.trimEnd() + `\n\n${empty}\n\n${frozen}`;
  fs.writeFileSync(file(), text);
  return { version, date };
}

module.exports = { update, release, commits };
